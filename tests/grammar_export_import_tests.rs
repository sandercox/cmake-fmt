#[test]
fn test_grammar_precedence() {
    // Test that precedence is maintained: config > grammar_file > auto-detected
    let temp_dir = TempDir::new().expect("Failed to create temp dir");
    let grammar_path = temp_dir.path().join("grammars.toml");

    // Create a grammar file that defines a custom command
    let grammar_content = r#"
[[grammar]]
command = "find_package"

[grammar.keywords]
CUSTOM_KEYWORD = "Flag"
"#;
    fs::write(&grammar_path, grammar_content).expect("Failed to write grammar file");

    // Create a config that also defines find_package
    let mut config = FormatConfig::default();
    config.grammar_files = vec![grammar_path];

    let mut grammar_config = cmake_fmt::formatter::CommandGrammarConfig::default();
    grammar_config.options = vec!["CONFIG_KEYWORD".to_string()];
    config.command_grammars.insert("find_package".to_string(), grammar_config);

    // Format with this config - the config grammar should take precedence
    let cmake_content = "find_package(CONFIG_KEYWORD CUSTOM_KEYWORD)\n";
    let (formatted, _warnings) = cmake_fmt::formatter::format_text_with_diagnostics(
        cmake_content,
        &config,
    );

    // Should not crash - precedence is working
    assert!(!formatted.is_empty());
}
